def create_invoice(supplier_name, invoice_number):
    """إنشاء فاتورة بـ 150 صنف"""

    wb = Workbook()
    ws = wb.active
    ws.title = "الفاتورة"
    ws.right_to_left = True

    # تعيين عرض الأعمدة
    widths = [15, 30, 10, 10, 12, 12, 12, 20, 15, 15, 10, 10]
    for i, width in enumerate(widths, 1):
        ws.column_dimensions[chr(64+i)].width = width

    # الرأس
    headers = ["الكود", "الوصف", "العبوة", "العدد", "التكلفة", "البيع", "الصلاحية", "المورد", "فرعي", "رئيسي", "الصندوق", "ب_الصندوق"]

    for i, header in enumerate(headers, 1):
        cell = ws.cell(row=1, column=i)
        cell.value = header
        cell.fill = PatternFill(start_color="FFC000", end_color="FFC000", fill_type="solid")
        cell.font = Font(bold=True, size=11)
        cell.alignment = Alignment(horizontal="center", vertical="center")

    # إضافة 150 صنف
    row = 2
    total = 0

    for i, product in enumerate(products[:150], 1):
        barcode = generate_barcode()
        packaging = random.randint(1, 10)
        quantity = random.randint(10, 100)
        cost = round(random.uniform(10, 200), 2)
        sell_price = round(cost * 1.2, 2)

        # تاريخ الصلاحية (MM/YYYY)
        months_ahead = random.randint(3, 12)
        expiry_date = (datetime.now() + timedelta(days=months_ahead*30)).strftime("%m/%Y")

        subtotal = round(quantity * cost, 2)
        total += subtotal

        # ملء البيانات
        ws[f'A{row}'] = barcode
        ws[f'B{row}'] = product['name']
        ws[f'C{row}'] = packaging
        ws[f'D{row}'] = quantity
        ws[f'E{row}'] = cost
        ws[f'F{row}'] = sell_price
        ws[f'G{row}'] = expiry_date
        ws[f'H{row}'] = supplier_name
        ws[f'I{row}'] = product['sub']
        ws[f'J{row}'] = product['main']
        ws[f'K{row}'] = None
        ws[f'L{row}'] = None

        # تنسيق
        for col in 'ABCDEFGHIJKL':
            ws[f'{col}{row}'].alignment = Alignment(horizontal="center", vertical="center")

        row += 1

    # إضافة الإجمالي
    ws[f'H{row+1}'] = "الإجمالي:"
    ws[f'I{row+1}'] = total

    # حفظ الملف على سطح المكتب
    filename = f"{supplier_name.replace(' ', '_')}_Invoice.xlsx"
    filepath = f"C:\\Users\\naji2\\Desktop\\{filename}"
    wb.save(filepath)

    print(f"✓ {filename} — {len(products[:150])} صنف")
    return filepath

