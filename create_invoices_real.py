def generate_barcode():
    """توليد باركود 12 رقم"""
    return ''.join([str(random.randint(0, 9)) for _ in range(12)])

def create_invoice(supplier_name, invoice_number):
    """إنشاء فاتورة بـ 150 صنف بالضبط"""

    # إنشاء Workbook
    wb = Workbook()
    ws = wb.active
    ws.title = "الفاتورة"

    # تعيين عرض الأعمدة
    ws.column_dimensions['A'].width = 15
    ws.column_dimensions['B'].width = 30
    ws.column_dimensions['C'].width = 10
    ws.column_dimensions['D'].width = 10
    ws.column_dimensions['E'].width = 10
    ws.column_dimensions['F'].width = 12
    ws.column_dimensions['G'].width = 12
    ws.column_dimensions['H'].width = 18
    ws.column_dimensions['I'].width = 12
    ws.column_dimensions['J'].width = 12
    ws.column_dimensions['K'].width = 18

    # تعريب القالب من اليمين لليسار
    ws.right_to_left = True

    # الرأس
    ws['A1'] = "الرقم"
    ws['B1'] = "الوصف"
    ws['C1'] = "الكمية"
    ws['D1'] = "الوحدة"
    ws['E1'] = "السعر"
    ws['F1'] = "صافي"
    ws['G1'] = "الصلاحية"
    ws['H1'] = "المورد"
    ws['I1'] = "فرعي"
    ws['J1'] = "رئيسي"
    ws['K1'] = "الفئة"

    # تنسيق الرأس
    header_fill = PatternFill(start_color="FFC000", end_color="FFC000", fill_type="solid")
    header_font = Font(bold=True, size=11)

    for col in ['A1', 'B1', 'C1', 'D1', 'E1', 'F1', 'G1', 'H1', 'I1', 'J1', 'K1']:
        ws[col].fill = header_fill
        ws[col].font = header_font
        ws[col].alignment = Alignment(horizontal="center", vertical="center")

    # إضافة 150 صنف بالضبط
    row = 2
    total = 0
    categories = {
        "أرز": "حبوب",
        "دقيق": "حبوب",
        "زيت": "زيوت",
        "سمن": "دهون",
        "حليب": "ألبان",
        "جبن": "ألبان",
        "سمك": "لحوم",
        "دجاج": "لحوم",
        "شوكولاتة": "حلويات",
        "حلوى": "حلويات",
        "شاي": "مشروبات",
        "قهوة": "مشروبات",
        "عصير": "مشروبات",
        "صلصة": "توابل",
        "لوز": "مكسرات",
        "تمر": "فواكه جافة",
        "كورن": "حبوب جاهزة",
        "معكرونة": "معكرونة",
        "خبز": "خبز",
        "ديتول": "تنظيف",
        "سائل جلي": "تنظيف",
        "حمام": "تنظيف",
        "مناديل": "تنظيف",
        "عطر": "عطور",
        "غسول": "عناية",
    }

    for i, product_name in enumerate(all_products[:150], 1):
        barcode = generate_barcode()
        quantity = random.randint(5, 100)
        unit = random.choice(["كج", "لتر", "علبة", "قطعة", "كيس", "غ", "مل", "قطع"])
        price = round(random.uniform(5, 500), 2)
        net_price = round(price * 0.95, 2)

        # تحديد الفئة بناءً على الكلمات المفتاحية
        category = "متنوع"
        for key, cat in categories.items():
            if key in product_name:
                category = cat
                break

        # تاريخ الصلاحية (من 3 أشهر إلى سنة من الآن)
        days_ahead = random.randint(90, 365)
        expiry_date = (datetime.now() + timedelta(days=days_ahead)).strftime("%d/%m/%Y")

        amount = round(quantity * price, 2)
        total += amount

        ws[f'A{row}'] = barcode
        ws[f'B{row}'] = product_name
        ws[f'C{row}'] = quantity
        ws[f'D{row}'] = unit
        ws[f'E{row}'] = price
        ws[f'F{row}'] = net_price
        ws[f'G{row}'] = expiry_date
        ws[f'H{row}'] = supplier_name
        ws[f'I{row}'] = amount
        ws[f'J{row}'] = round(amount * 1.05, 2)
        ws[f'K{row}'] = category

        # تنسيق الخلايا
        for col in ['A', 'B', 'C', 'D', 'E', 'F', 'G', 'H', 'I', 'J', 'K']:
            ws[f'{col}{row}'].alignment = Alignment(horizontal="center", vertical="center")

        row += 1

    # إضافة الإجمالي
    total_row = row + 1
    ws[f'H{total_row}'] = "الإجمالي:"
    ws[f'I{total_row}'] = total
    ws[f'J{total_row}'] = round(total * 1.05, 2)

    total_fill = PatternFill(start_color="FFEB9C", end_color="FFEB9C", fill_type="solid")
    total_font = Font(bold=True)

    for col in ['H', 'I', 'J']:
        ws[f'{col}{total_row}'].fill = total_fill
        ws[f'{col}{total_row}'].font = total_font

    # حفظ الملف باسم المورد
    filename = f"{supplier_name.replace(' ', '_')}_invoice_{invoice_number}.xlsx"
    filepath = f"C:\\Users\\naji2\\DataLY_6\\{filename}"
    wb.save(filepath)

    print(f"✓ تم إنشاء: {filename} بـ 150 صنف حقيقي")
    return filepath

# إنشاء 5 فواتير
print("جاري إنشاء 5 فواتير بـ 150 صنف حقيقي لكل فاتورة...\n")
for i, supplier in enumerate(suppliers, 1):
    create_invoice(supplier, i)

