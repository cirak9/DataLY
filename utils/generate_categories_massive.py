# 2. التوليد الذكي
# ==============================================================================

def expand_keywords(base_words, qualities, sizes, brands, limit=3000):
    """توليد تركيبات محدودة لكل فئة"""
    keywords = set()

    for i, word in enumerate(base_words):
        keywords.add(word)

        # مع كل الأحجام
        for size in sizes:
            keywords.add(f"{word} {size}")
            keywords.add(f"{size} {word}")
            # مع الجودة
            for quality in qualities:
                keywords.add(f"{word} {quality} {size}")
                keywords.add(f"{size} {word} {quality}")

        # مع الماركة
        for brand in brands:
            keywords.add(f"{brand} {word}")
            keywords.add(f"{word} {brand}")
            # مع الحجم
            for size in sizes[:5]:
                keywords.add(f"{brand} {word} {size}")

        # تنويع إضافي
        if len(base_words) > 1:
            for j in range(1, min(4, len(base_words) - i)):
                next_word = base_words[(i + j) % len(base_words)]
                if word != next_word:
                    keywords.add(f"{word} و {next_word}")

    # قطع إذا تجاوزنا الحد
    if len(keywords) > limit:
        keyword_list = sorted(list(keywords))
        return keyword_list[:limit]

    return list(keywords)


